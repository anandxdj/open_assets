"use client";

import { useEffect, useState } from "react";
import { FlaskConical } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Notice } from "@/components/ui/feedback";
import { demoModeMessage, PLACEHOLDER_LABEL, type AiStatus } from "@/lib/demo-mode";
import { cn } from "@/lib/utils";

// One request per page load, shared by every component that asks. The server decides whether it is
// in demo mode (/api/studio/status); the browser never infers it from an environment variable.
let cached: AiStatus | null = null;
let inflight: Promise<AiStatus | null> | null = null;

function loadStatus(): Promise<AiStatus | null> {
  inflight ??= fetch("/api/studio/status", { cache: "no-store" })
    .then((res) => (res.ok ? (res.json() as Promise<AiStatus>) : null))
    .catch(() => null)
    .then((status) => {
      cached = status;
      // A failed lookup is retried by the next component that mounts.
      if (!status) inflight = null;
      return status;
    });
  return inflight;
}

/** The server's AI status, or null until it answers (and when it cannot be reached). */
export function useAiStatus(): AiStatus | null {
  const [status, setStatus] = useState<AiStatus | null>(cached);
  useEffect(() => {
    if (cached) return;
    let live = true;
    void loadStatus().then((next) => {
      if (live && next) setStatus(next);
    });
    return () => {
      live = false;
    };
  }, []);
  return status;
}

/** Calm notice for the foot of a generator form, next to its Generate button. Renders nothing for real results. */
export function DemoModeNotice({ className }: { className?: string }) {
  const message = demoModeMessage(useAiStatus());
  if (!message) return null;
  return (
    <Notice tone="info" role="status" className={cn("text-[11px] leading-4", className)}>
      <strong className="font-bold">Demo mode.</strong> {message}
    </Notice>
  );
}

/** Small outlined label for a result the server made up. Renders nothing for real results. */
export function PlaceholderLabel({ className }: { className?: string }) {
  const status = useAiStatus();
  if (!status?.mock) return null;
  return (
    <Badge tone="info" className={className} title="Made up by demo mode, not generated by an AI provider">
      <FlaskConical aria-hidden />
      {PLACEHOLDER_LABEL}
    </Badge>
  );
}
